// Generate each WASM package's `auto.js` — the entry point that decides which
// binary to instantiate.
//
//   node scripts/write-wasm-selector.mjs            # build has a fallback
//   node scripts/write-wasm-selector.mjs --none     # SIMD-only build
//
// Why generated rather than written by hand: the fallback is only built for
// publishable builds (`build-all`), and a hand-written selector would have to
// reference `<crate>_bg.nosimd.wasm` unconditionally. Any static reference —
// an `import ... ?url`, or `new URL()` that a bundler can analyse — forces the
// file to exist in *every* build, which is what previously made dev builds
// carry a fallback they had no use for. Generating the module lets the
// SIMD-only variant simply not mention the file, so there is nothing to
// resolve and nothing to build.
//
// The selector lives inside the package so the URL resolves relative to the
// binaries next to it, and so consumers keep calling a plain `init()`.
import { existsSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const withFallback = !process.argv.includes("--none");

/** crate -> the web/wasm directory holding its artifacts. */
const MODULES = [
  ["navara_wasm", "navara_engine"],
  ["navara_wasm_worker", "navara_engine_worker"],
  ["navara_wasm_font_worker", "navara_font_worker"],
  ["navara_wasm_api", "navara_engine_api"],
];

const HEADER = `// GENERATED by scripts/write-wasm-selector.mjs — do not edit.\n`;

/**
 * `i32.const 0` / `i8x16.splat` / `i8x16.popcnt`: a module whose only function
 * returns a v128. Runtimes without `simd128` reject it during validation.
 * Inlined rather than imported so the published package stays dependency-free.
 */
const PROBE = `new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x05, 0x01, 0x60,
  0x00, 0x01, 0x7b, 0x03, 0x02, 0x01, 0x00, 0x0a, 0x0a, 0x01, 0x08, 0x00,
  0x41, 0x00, 0xfd, 0x0f, 0xfd, 0x62, 0x0b,
])`;

const selectorWithFallback = (crate) => `${HEADER}
// This build ships both binaries. Probe once, then instantiate whichever the
// runtime can load. Validation only — nothing is fetched or instantiated here,
// so it is safe on the main thread and inside workers, where it must run
// separately because each worker loads its own WASM.
import init from "./${crate}.js";

const SIMD_PROBE = ${PROBE};

let simd;
function hasSimd() {
  if (simd === undefined) {
    try {
      simd = WebAssembly.validate(SIMD_PROBE);
    } catch {
      simd = false;
    }
  }
  return simd;
}

export default function initAuto(moduleOrPath) {
  if (moduleOrPath !== undefined) return init(moduleOrPath);
  return init(
    hasSimd()
      ? undefined
      : { module_or_path: new URL("./${crate}_bg.nosimd.wasm", import.meta.url) },
  );
}
`;

const selectorSimdOnly = (crate) => `${HEADER}
// This build contains only the SIMD module, so there is nothing to select
// between and no reference to a fallback binary. A runtime without \`simd128\`
// fails at instantiation, which is the correct signal for a non-publishable
// build. \`cargo make build-all\` produces the variant that can fall back.
export { default } from "./${crate}.js";
`;

const types = (crate) => `${HEADER}export { default } from "./${crate}.js";\n`;

for (const [crate, pkg] of MODULES) {
  const dir = resolve(root, "web/wasm", pkg);
  if (!existsSync(dir)) continue;
  writeFileSync(
    resolve(dir, "auto.js"),
    withFallback ? selectorWithFallback(crate) : selectorSimdOnly(crate),
  );
  writeFileSync(resolve(dir, "auto.d.ts"), types(crate));

  if (!withFallback) {
    // Nothing references it now, and leaving it would let a stale binary be
    // published alongside a selector that never reaches for it.
    const stale = resolve(dir, `${crate}_bg.nosimd.wasm`);
    if (existsSync(stale)) rmSync(stale);
  }
}

console.log(
  withFallback
    ? "wasm selectors: SIMD with non-SIMD fallback"
    : "wasm selectors: SIMD only (no fallback in this build)",
);
